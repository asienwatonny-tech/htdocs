<?php
require 'includes/auth.php';
require_role(['receptionist','nurse','doctor','lab','pharmacy','admin']);
$uid = (int)$_SESSION['user']['id'];
$forced = !empty($_SESSION['user']['must_change']);
$err = '';
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
  csrf_check();
  $cur = $_POST['current'] ?? ''; $new = $_POST['new'] ?? ''; $again = $_POST['again'] ?? '';
  $s = $db->prepare("SELECT password_hash FROM staff WHERE id=?"); $s->execute([$uid]);
  $hash = (string)$s->fetchColumn();
  if (!password_verify($cur, $hash))        $err = 'Your current password is not correct.';
  elseif ($new !== $again)                  $err = 'The two new passwords do not match.';
  elseif ($new === $cur)                    $err = 'Choose a password different from the current one.';
  elseif (($p = password_problem($new)) !== '') $err = $p;
  else {
    $db->prepare("UPDATE staff SET password_hash=?, must_change_password=0 WHERE id=?")->execute([password_hash($new, PASSWORD_DEFAULT), $uid]);
    $_SESSION['user']['must_change'] = 0;
    session_regenerate_id(true);
    audit($db, $uid, 'password_changed', '');
    set_flash('ok', 'Password changed.');
    $role = $_SESSION['user']['role'];
    header('Location: /medflow/' . ($role === 'admin' ? 'admin/reports.php' : 'staff/dashboard.php')); exit;
  }
}
$title = 'Change password';
require 'includes/header.php';
?>
<div class="card narrow">
  <h2>Change password</h2>
  <?php if ($forced): ?><div class="msg">Your password was generated by the system. Choose your own password now to continue.</div><?php endif; ?>
  <?php if ($err): ?><div class="msg err"><?= e($err) ?></div><?php endif; ?>
  <form method="post" autocomplete="off">
    <?= csrf_field() ?>
    <label>Current (or generated) password</label><input name="current" type="password" required autocomplete="current-password">
    <label>New password</label><input name="new" type="password" required autocomplete="new-password">
    <label>Repeat new password</label><input name="again" type="password" required autocomplete="new-password">
    <p class="muted"><small>At least 8 characters with capital letters, small letters and numbers.</small></p>
    <button>Save new password</button>
  </form>
</div>
<?php require 'includes/footer.php'; ?>
